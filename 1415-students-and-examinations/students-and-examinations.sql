SELECT
    S.STUDENT_ID,
    S.STUDENT_NAME,
    B.SUBJECT_NAME,
    COUNT(E.SUBJECT_NAME) AS ATTENDED_EXAMS
FROM STUDENTS AS S
CROSS JOIN SUBJECTS AS B
LEFT JOIN EXAMINATIONS AS E
    ON S.STUDENT_ID = E.STUDENT_ID
    AND B.SUBJECT_NAME = E.SUBJECT_NAME
GROUP BY
    S.STUDENT_ID,
    S.STUDENT_NAME,
    B.SUBJECT_NAME
ORDER BY
    S.STUDENT_ID,
    B.SUBJECT_NAME;